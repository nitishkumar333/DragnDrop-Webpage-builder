// Exports the element/block templates from src/lib/element-factory.ts (and the
// curated fonts from src/lib/design-tokens.ts) to JSON for the Python backend,
// so the AI assistant inserts exactly the same designs as the editor.
//
//   npm run export:templates          write backend/app/ai/element_templates.json
//   npm run export:templates -- --check   fail if the JSON is out of date
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outFile = path.join(root, "backend", "app", "ai", "element_templates.json");
// Inside node_modules so the transpiled files can resolve packages like uuid.
const buildDir = path.join(root, "node_modules", ".cache", "element-templates");

const SOURCES = ["constants.ts", "design-tokens.ts", "element-factory.ts"];
const KINDS = [
  "text", "heading", "button", "link", "image", "video", "divider", "spacer",
  "contactForm", "container", "2Col",
  "navbar", "hero", "features", "testimonial", "pricing", "cta", "footer", "grid",
];

fs.mkdirSync(buildDir, { recursive: true });
for (const file of SOURCES) {
  const source = fs.readFileSync(path.join(root, "src", "lib", file), "utf8");
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2019 },
  });
  fs.writeFileSync(path.join(buildDir, file.replace(/\.ts$/, ".js")), outputText);
}

const require = createRequire(path.join(buildDir, "index.js"));
const { createElement } = require("./element-factory.js");
const { FONT_OPTIONS } = require("./design-tokens.js");

/** Drop ids; the backend assigns fresh ones every time it inserts a template. */
const stripIds = ({ id, ...el }) => ({
  ...el,
  content: Array.isArray(el.content) ? el.content.map(stripIds) : el.content,
});

const templates = {};
for (const kind of KINDS) {
  const element = createElement(kind);
  if (!element) throw new Error(`createElement("${kind}") returned null`);
  templates[kind] = stripIds(element);
}

const json =
  JSON.stringify(
    {
      $comment: "Generated by scripts/export-element-templates.mjs. Do not edit by hand.",
      fonts: FONT_OPTIONS.map(({ label, value }) => ({ label, value })),
      templates,
    },
    null,
    2
  ) + "\n";

if (process.argv.includes("--check")) {
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8") : "";
  if (current.replace(/\r\n/g, "\n") !== json) {
    console.error("element_templates.json is out of date. Run: npm run export:templates");
    process.exit(1);
  }
  console.log("element_templates.json is up to date.");
} else {
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, json);
  console.log(`Wrote ${path.relative(root, outFile)} (${KINDS.length} templates)`);
}
